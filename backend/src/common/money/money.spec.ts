import { formatMoneyText, money, roundMoney } from './money';

describe('roundMoney', () => {
  it.each([
    ['14.775', '14.78'],
    ['0.385', '0.39'],
    ['3.625', '3.63'],
    ['8.7875', '8.79'],
    ['1.5005', '1.50'],
    ['1.002', '1.00'],
    ['0.384', '0.38'],
    ['0.386', '0.39'],
    ['14.774', '14.77'],
    ['14.7749999', '14.77'],
    ['-0.385', '-0.39'],
    ['-0.384', '-0.38'],
    ['-14.775', '-14.78'],
    ['-14.774', '-14.77'],
    ['0', '0.00'],
    ['0.005', '0.01'],
    ['0.004', '0.00'],
    ['40', '40.00'],
  ])('arredonda %s para %s', (value, expected) => {
    expect(roundMoney(money(value)).toFixed(2)).toBe(expected);
  });
});

describe('formatMoneyText', () => {
  it.each([
    ['0', '0,00'],
    ['1', '1,00'],
    ['38.85', '38,85'],
    ['130.575', '130,58'],
    ['-45.55', '-45,55'],
    ['1744.14', '1744,14'],
  ])('%s → %s', (value, text) => {
    expect(formatMoneyText(money(value))).toBe(text);
  });
});
